export interface LabeledTrainingRecord {
  tenure: number;
  monthly_charges: number;
  contract_code: number;
  support_calls: number;
  echeck_flag: number;
  fiber_flag: number;
  tech_support_flag: number;
  usage_score: number;
  nps_score: number;
  churned: 0 | 1;
}

function createRng(seed: number) {
  let state = seed >>> 0;
  return () => {
    state |= 0;
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function generateCalibrationDataset(count = 300): LabeledTrainingRecord[] {
  const rand = createRng(20261118);
  const rows: LabeledTrainingRecord[] = [];

  for (let i = 0; i < count; i++) {
    const rContract = rand();
    const contract_code = rContract < 0.52 ? 0 : rContract < 0.78 ? 1 : 2;

    const tenure =
      contract_code === 0
        ? Math.max(1, Math.round(rand() * 24))
        : contract_code === 1
          ? Math.max(4, Math.round(6 + rand() * 38))
          : Math.max(12, Math.round(18 + rand() * 54));

    const fiber_flag = rand() < 0.55 ? 1 : 0;
    const baseCharge = fiber_flag ? 72 + rand() * 55 : 35 + rand() * 40;
    const monthly_charges = Math.round(baseCharge * 10) / 10;

    const tech_support_flag = contract_code === 2 ? (rand() < 0.78 ? 1 : 0) : rand() < 0.42 ? 1 : 0;
    const echeck_flag = contract_code === 0 ? (rand() < 0.62 ? 1 : 0) : rand() < 0.2 ? 1 : 0;

    const support_calls = Math.min(
      9,
      Math.max(
        0,
        Math.round(
          (contract_code === 0 ? 2.6 : 1.1) +
            (tech_support_flag === 0 ? 1.4 : -0.5) +
            (rand() - 0.35) * 4.5
        )
      )
    );

    const usage_score = Math.min(
      98,
      Math.max(
        12,
        Math.round(
          52 +
            contract_code * 13 +
            Math.min(20, tenure * 0.35) -
            support_calls * 5.2 +
            (rand() - 0.5) * 28
        )
      )
    );

    const nps_score = Math.min(
      10,
      Math.max(
        1,
        Math.round(
          5.8 +
            (usage_score - 55) * 0.055 -
            support_calls * 0.45 +
            (rand() - 0.5) * 2.4
        )
      )
    );

    let logOdds = -0.35;
    logOdds += contract_code === 0 ? 1.15 : contract_code === 1 ? -0.45 : -1.45;
    logOdds += tenure < 6 ? 1.05 : tenure < 14 ? 0.35 : -0.042 * (tenure - 14);
    logOdds += (monthly_charges - 70) * 0.026;
    logOdds += (support_calls - 2) * 0.52;
    logOdds += echeck_flag ? 0.58 : -0.22;
    logOdds += fiber_flag && tech_support_flag === 0 ? 0.65 : 0;
    logOdds += tech_support_flag ? -0.55 : 0.25;
    logOdds += (55 - usage_score) * 0.036;
    logOdds += (6 - nps_score) * 0.26;

    if (tenure <= 8 && support_calls >= 4) logOdds += 0.95;
    if (tenure >= 30 && contract_code === 2 && usage_score >= 75) logOdds -= 0.85;

    const trueProb = 1 / (1 + Math.exp(-logOdds));
    const churned: 0 | 1 = rand() < trueProb ? 1 : 0;

    rows.push({
      tenure,
      monthly_charges,
      contract_code,
      support_calls,
      echeck_flag,
      fiber_flag,
      tech_support_flag,
      usage_score,
      nps_score,
      churned,
    });
  }

  return rows;
}
